const assert = require('node:assert/strict');
global.window = globalThis;
const M = require('../dist/planner/calendar-model.js');
const S = require('../dist/planner/schedule.js');
require('../dist/planner/priority.js');
const T = require('../dist/planner/today-plan.js');
const day = '2026-10-19', now = new Date('2026-10-19T08:00:00');
const state = { organization: { availability: { 1: [{start:'09:00',end:'14:00'}] } }, events: [
  {id:'work',type:'work',title:'Turno',date:day,time:'11:00',endTime:'12:00'},
  {id:'exam',type:'exam',subject:'organica',title:'Prueba',date:'2026-10-22',status:'planned'}
], grades: {}, sessions: [] };
const schedule = [{day:1,start:'09:00',end:'10:00',name:'Clase'}];
const info = S.dayInfo(state, day, schedule, now);
assert.deepEqual(info.free,[{start:600,end:660},{start:720,end:840}]);
assert.equal(info.available,180);
assert.equal(info.conflicts.length,0);
assert.deepEqual(S.subtract([{start:0,end:100},{start:50,end:150}],[{start:30,end:60}]),[{start:0,end:30},{start:60,end:150}]);
const assigned = S.allocate([{minutes:50},{minutes:50},{minutes:50}],info,{breakMinutes:10,limit:120});
assert.deepEqual(assigned.map(b=>b.start),['10:00','12:00','13:00']);
assert.equal(assigned[2].minutes,20); assert.equal(assigned[2].remainingMinutes,30);
assert.equal(assigned.reduce((n,b)=>n+(b.start?b.minutes:0),0),120);
assert.ok(S.allocate([{minutes:50},{minutes:50},{minutes:50},{minutes:50}],info,{limit:120})[3].unplaced);
assert.ok(S.allocate([{minutes:30}],{...info,configured:false})[0].unplaced);
assert.ok(S.allocate([{minutes:30,event:{date:day,time:'09:00'}}],info)[0].unplaced,'no prepara una evaluación después de su hora');
assert.equal(S.allocate([{minutes:30,event:{date:day,time:'10:15'}}],info)[0].remainingMinutes,15,'recorta la preparación al horario de la evaluación');
assert.equal(S.dayInfo(state,day,schedule,new Date('2026-10-19T13:30:00')).available,30,'no propone horas pasadas');
state.events.push({id:'activity',date:day,type:'personal',title:'Actividad',time:'11:30',endTime:'12:30'});
assert.equal(S.dayInfo(state,day,schedule,now).conflicts.length,1,'detecta el choque entre compromisos');
state.events.push({id:'unknown',date:day,title:'Sin término',time:'13:00'});
assert.equal(S.dayInfo(state,day,schedule,now).warnings.length,1);
assert.ok(S.allocate([{minutes:30}],S.dayInfo(state,day,schedule,now))[0].unplaced,'no promete huecos con duraciones desconocidas');
assert.match(S.validateEvent({title:'Trabajo',date:day,type:'work',time:'20:00',endTime:'18:00'}),/posterior/);
assert.match(S.validateEvent({title:'Trabajo',date:day,type:'work'}),/inicio y término/);
let serial = 0; const uid = p => `${p}-${++serial}`;
const fresh = { events:[], grades:{} }, draft = { title:'Turno',date:day,type:'work',time:'10:00',endTime:'12:00',subject:'organica' };
const r = S.saveEvent(fresh,draft,{count:3,uid,today:day});
assert.ok(r.ok); assert.equal(fresh.events.length,3); assert.ok(fresh.events.every(e=>e.subject==='personal'&&e.durationMinutes===120));
const series = fresh.events[0].series;
S.saveEvent(fresh,draft,{count:2,uid,today:day});
assert.notEqual(fresh.events[3].series,series,'dos series el mismo día no se confunden');
const first = fresh.events[0];
const edit = S.saveEvent(fresh,{...draft,date:'2026-10-20',title:'Turno nuevo'},{id:first.id,scope:'following',uid,today:day});
assert.deepEqual(fresh.events.slice(0,3).map(e=>e.date),['2026-10-20','2026-10-27','2026-11-03']);
assert.equal(fresh.events[3].title,'Turno','no toca la otra serie');
assert.equal(fresh.events[0].dateHistory.length,1);
edit.revert(); assert.equal(fresh.events[0].date,day);
const before = JSON.stringify(fresh);
assert.equal(S.saveEvent(fresh,{...draft,endTime:'09:00'},{count:4,uid}).ok,false);
assert.equal(JSON.stringify(fresh),before,'validación atómica de una serie');
const members = S.seriesMembers(fresh.events,fresh.events[1],'following'); assert.equal(members.length,2);
const ranks = NexoPriority.rank(state.events,{today:day});
assert.ok(ranks.every(r=>!['work','personal'].includes(r.event.type)),'trabajo ocupa tiempo, no se convierte en estudio');
const overdue={id:'late',type:'deadline',date:'2026-10-18',title:'Informe',subject:'organica'};
const latePlan=T.plan({today:day,ranked:NexoPriority.rank([overdue],{today:day}),minutes:30});
assert.equal(latePlan[0].event.id,'late','recupera entregas pendientes vencidas');
assert.deepEqual(T.plan({today:day,ranked:ranks,minutes:0}),[]);
assert.ok(T.plan({today:day,ranked:ranks,minutes:15}).reduce((n,b)=>n+b.minutes,0)<=15);
const freeState={...state,events:state.events.slice(0,2),organization:{...state.organization,schedule,minutes:{1:120}}};
const bridge={state:freeState,ranked:d=>NexoPriority.rank(freeState.events,{today:d})};
const result=T.planDay(bridge,'2026-10-19'); assert.ok(result.length);
assert.ok(result.every(b=>!b.start||S.time(b.end)<=14*60));
assert.deepEqual(JSON.parse(JSON.stringify(fresh)),fresh,'datos de series serializables');
console.log('Organizador: intervalos, choques, pausas, límites, pendientes, series e historial OK.');
